#!/bin/sh
# hosting.sh – signs the demo hosting's customer zones (zones/hosting.list) and delivers them to auth1.
# Every zone is signed correctly, except those with a start error in the list, which break.sh
# breaks ("zone" mode). That is the hosting the web app shows when the demo starts.
#
# You normally don't run it by hand: sign.sh calls it after the broken zones and before test.,
# because test. needs these zones' DS records (build/parent-ds/<zone>.ds).
#
# Output:
#   build/hosting/<zone>.zone.signed   delivered to auth1/
#   build/parent-ds/<zone>.ds          the DS for test.
#   auth1/hosting.conf                 the zones' blocks for NSD (auth1/nsd.conf includes it)
#
# The delegations in test. come from the same list (sign-tld.sh).

set -eu
cd "$(dirname "$0")/.."

KEYDIR=keys
SRC=zones
BUILD=build
OUT=$BUILD/hosting
LIST=$SRC/hosting.list
SIG_START=${SIG_START:-now-3600}
SIG_END=${SIG_END:-now+2592000}

rm -rf "$OUT"
mkdir -p "$OUT" "$BUILD/parent-ds"

{
    echo "# Generated by scripts/hosting.sh from zones/hosting.list – don't edit."
    awk '!/^#/ && NF { printf "\nzone:\n    name: \"%s.\"\n    zonefile: \"%s.zone.signed\"\n", $1, $1 }' "$LIST"
} > auth1/hosting.conf

awk '!/^#/ && NF { print $1, ($2 == "" ? "-" : $2) }' "$LIST" | while read -r z start; do
    if [ "$start" = - ]; then
        dnssec-signzone -S -K "$KEYDIR" -d "$BUILD" -s "$SIG_START" -e "$SIG_END" -N unixtime \
            -o "$z" -f "$OUT/$z.zone.signed" "$SRC/$z.zone" >/dev/null
        dnssec-verify -q -o "$z" "$OUT/$z.zone.signed"
        cp "$BUILD/dsset-$z." "$BUILD/parent-ds/$z.ds"
    else
        sh scripts/break.sh zone "$z" "$start" >/dev/null
        echo ">> hosting: $z starts with $start"
    fi
done

cp "$OUT"/*.zone.signed auth1/
echo ">> hosting: $(grep -c '^zone:' auth1/hosting.conf) customer zones in auth1/"
